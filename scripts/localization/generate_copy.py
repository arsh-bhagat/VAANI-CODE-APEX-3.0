"""Generate the bundled Kotlin UI catalog. No network or Android build required."""
import csv
import json
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CATALOG = Path(__file__).with_name("ui-copy.psv")
OUTPUT = ROOT / "app/src/main/java/com/bithead/shelter/ui/localization/UiCopy.kt"


def entries():
    with CATALOG.open(encoding="utf-8", newline="") as handle:
        rows = list(csv.reader(handle, delimiter="|"))[1:]
    for number, row in enumerate(rows, 2):
        if len(row) != 3 or not all(row):
            raise ValueError(f"Invalid translation row {number}")
    return [[value.replace(r"\n", "\n") for value in row] for row in rows]


def render():
    def literal(value):
        return json.dumps(value, ensure_ascii=False).replace("$", r"\$")
    lines = ["package com.bithead.shelter.ui.localization", "",
             "// Generated by scripts/localization/generate_copy.py from ui-copy.psv.",
             "internal val uiCopy = listOf("]
    lines += ["    UiCopy(" + ", ".join(map(literal, row)) + ")," for row in entries()]
    return "\n".join(lines + [")", ""])


def generate_walkthrough():
    with Path(__file__).with_name("walkthrough.psv").open(encoding="utf-8", newline="") as handle:
        rows = list(csv.reader(handle, delimiter="|"))[1:]
    for index, code in enumerate(("hi", "mr"), 1):
        resources = ET.Element("resources")
        for row in rows:
            if len(row) != 3 or not all(row):
                raise ValueError("Incomplete walkthrough translation")
            element = ET.SubElement(resources, "string", name=row[0])
            element.text = row[index].replace("'", r"\'").replace('"', r'\"')
        ET.indent(resources, space="    ")
        output = ROOT / f"app/src/main/res/values-{code}/walkthrough.xml"
        output.parent.mkdir(exist_ok=True)
        ET.ElementTree(resources).write(output, encoding="utf-8", xml_declaration=True)


if __name__ == "__main__":
    OUTPUT.write_text(render(), encoding="utf-8")
    generate_walkthrough()
    web_copy = {row[0].lower(): {"hi": row[1], "mr": row[2]} for row in entries()}
    (ROOT / "app/src/main/assets/ui_copy.js").write_text(
        "// Generated from scripts/localization/ui-copy.psv. Bundled; no translation service.\n"
        "window.vaaniUiCopy = " + json.dumps(web_copy, ensure_ascii=False) + ";\n", encoding="utf-8")
    print(f"Generated {len(entries())} bundled English/Hindi/Marathi entries")
